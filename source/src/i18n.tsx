type LanguageContextValue = {
  language: Language;
  setLanguage(language: Language): void;
  t(text: string): string;
};
const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

function translate(text: string, language: Language): string {
  if (language === "es") return text;
  const source = text.trim();
  let translated = translations[source];
  if (!translated) {
    const field = /^Revisa el campo (.+) \(máximo (\d+)\)\.$/.exec(source);
    const selection = /^Selección inválida: (.+)\.$/.exec(source);
    const choice = /^Valor inválido: (.+)\.$/.exec(source);
    if (field) translated = `Check the ${field[1]} field (maximum ${field[2]}).`;
    else if (selection) translated = `Invalid selection: ${selection[1]}.`;
    else if (choice) translated = `Invalid value: ${choice[1]}.`;
  }
  return translated ? text.replace(source, translated) : text;
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try { return localStorage.getItem("marker-language") === "es" ? "es" : "en"; }
    catch { return "en"; }
  });
  useEffect(() => {
    document.documentElement.lang = language;
    try { localStorage.setItem("marker-language", language); } catch { /* Preferences work without storage. */ }
  }, [language]);
  return <LanguageContext.Provider value={{ language, setLanguage, t: (text) => translate(text, language) }}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("LanguageProvider is required");
  return value;
}
